#!/usr/bin/env node
// Fork-only. Writes api/_fork-feeds.js: the tech edition's feeds from
// shared/news-catalog.json, for the keyless digest in api/fork-digest.js.
import { readFileSync, writeFileSync } from 'node:fs';

const catalog = JSON.parse(readFileSync(new URL('../shared/news-catalog.json', import.meta.url), 'utf8'));
const feeds = [];
for (const feed of catalog.feeds) {
  for (const placement of feed.placements) {
    if (placement.edition !== 'tech' || typeof feed.url !== 'string') continue;
    feeds.push({ name: feed.name, url: feed.url, category: placement.category });
  }
}
const categories = catalog.layout.server.tech;
writeFileSync(
  new URL('../api/_fork-feeds.js', import.meta.url),
  `// Generated by scripts/fork-feeds.mjs. Do not edit.\nexport const CATEGORIES = ${JSON.stringify(categories)};\nexport const FEEDS = ${JSON.stringify(feeds, null, 2)};\n`,
);
console.log(`fork feeds: ${feeds.length} feeds, ${categories.length} categories`);
